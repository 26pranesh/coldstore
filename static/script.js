// Price Estimator Logic
function calculateEstimate() {
    const service = document.getElementById('calcService').value;
    const dist = parseFloat(document.getElementById('calcDistance').value) || 0;
    const weight = parseFloat(document.getElementById('calcWeight').value) || 0;
    const paramLabel = document.getElementById('calcParamLabel');
    const currentLang = document.getElementById('languageSelect').value;

    let totalFare = 0;

    if (service === 'refrig') {
        paramLabel.innerText = currentLang === 'en' ? "Distance (Approx KM)" : (currentLang === 'ne' ? "दूरी (Approx KM)" : "दूरी (Approx KM)");
        totalFare = 1200 + (dist * 25) + (weight * 400);
    } else if (service === 'dry') {
        paramLabel.innerText = currentLang === 'en' ? "Distance (Approx KM)" : (currentLang === 'ne' ? "दूरी (Approx KM)" : "दूरी (Approx KM)");
        totalFare = 800 + (dist * 18) + (weight * 300);
    } else if (service === 'coldroom') {
        paramLabel.innerText = currentLang === 'en' ? "Storage Days (Days)" : (currentLang === 'ne' ? "स्टोरेज दिन (Days)" : "स्टोरेज दिन (Days)");
        totalFare = (dist * weight * 10 * 15) + 500;
    }

    document.getElementById('estPrice').innerText = '₹ ' + Math.round(totalFare).toLocaleString('en-IN');
}

// Initialize Calculator
calculateEstimate();